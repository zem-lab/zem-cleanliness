module.exports = async ({ page, assert, log }) => {
  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.getByRole('heading', { name: '首页', exact: true }).waitFor()
  assert(await page.getByAltText('ZEPTOOLS').isVisible(), 'official ZEPTOOLS logo is visible')
  assert(await page.getByText('正极极片 A17').first().isVisible(), 'current task is visible')
  assert(await page.getByText('今日统计').count() === 0, 'home statistics card is removed')
  assert(await page.getByRole('heading', { name: '设备状态' }).count() === 0, 'home device card is removed')
  await page.screenshot({ path: 'playwright-artifacts/simple-home.png', fullPage: true })
  log('home=ok')

  await page.getByRole('button', { name: '新建检测任务' }).click()
  await page.getByRole('heading', { name: '新建任务', exact: true }).waitFor()
  assert(await page.getByText('positive_A17_particles.json').isVisible(), 'imported JSON is visible')
  assert(await page.getByText('最多执行').count() === 0, 'execution limit field is removed')
  await page.screenshot({ path: 'playwright-artifacts/simple-task.png', fullPage: true })
  log('task=ok')

  await page.getByRole('button', { name: /下一步：坐标标定/ }).click()
  await page.getByRole('heading', { name: '坐标标定', exact: true }).waitFor()
  assert(await page.getByText('匹配证据').isVisible(), 'multi-particle evidence is visible')
  await page.getByRole('button', { name: 'AB 点法' }).click()
  assert(await page.getByText('fixture_det_v3_best.onnx').isVisible(), 'fixture model is visible')
  assert(await page.getByText('hole_det_v3_best.onnx').isVisible(), 'hole model is visible')
  await page.screenshot({ path: 'playwright-artifacts/simple-calibration.png', fullPage: true })
  log('calibration_modes=ok')

  await page.getByRole('button', { name: '检测运行', exact: true }).click()
  await page.getByRole('heading', { name: '检测运行', exact: true }).waitFor()
  await page.getByRole('button', { name: /继续检测/ }).click()
  assert(await page.getByText('正在运行').isVisible(), 'running state is visible')
  await page.screenshot({ path: 'playwright-artifacts/simple-running.png', fullPage: true })
  log('running=ok')

  await page.getByRole('button', { name: '报告记录', exact: true }).click()
  await page.getByRole('heading', { name: '报告记录', exact: true }).waitFor()
  assert(await page.getByPlaceholder('搜索任务编号或样品名称').isVisible(), 'report search is visible')
  log('reports=ok')

  await page.getByRole('button', { name: '系统设置', exact: true }).click()
  await page.getByRole('heading', { name: '系统设置', exact: true }).waitFor()
  assert(await page.getByText('particle_yolo11n_seg_reann_20260811_best.onnx').isVisible(), 'particle model is visible')
  assert(await page.getByText('fixture_det_v3_best.onnx').isVisible(), 'fixture model is packaged')
  assert(await page.getByText('hole_det_v3_best.onnx').isVisible(), 'hole model is packaged')
  assert(await page.getByText('任务结束后自动关枪').count() === 0, 'automatic gun shutdown option is removed')
  await page.screenshot({ path: 'playwright-artifacts/simple-settings.png', fullPage: true })
  log('settings=ok')

  await page.getByRole('button', { name: /电镜已连接/ }).click()
  assert(await page.getByRole('heading', { name: '设备状态' }).isVisible(), 'device drawer is visible')
  log('device_drawer=ok')
}
